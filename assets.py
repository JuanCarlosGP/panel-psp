"""Generate the embedded bitmap fonts and the Memory Stick icon."""

from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


HERE = Path(__file__).resolve().parent
FONTS = Path("/usr/share/fonts/liberation")
CHARACTERS = [chr(code) for code in range(32, 127)] + list("áéíóúñÁÉÍÓÚÑüÜ·")


def font_data(name, filename, size):
    font = ImageFont.truetype(str(FONTS / filename), size)
    pixels = bytearray()
    metrics = []
    for char in CHARACTERS:
        left, top, right, bottom = font.getbbox(char, anchor="ls")
        width, height = right - left, bottom - top
        metrics.append((ord(char), left, top, width, height, round(font.getlength(char)), len(pixels)))
        if width > 0 and height > 0:
            mask = Image.new("L", (width, height))
            ImageDraw.Draw(mask).text((-left, -top), char, anchor="ls", font=font, fill=255)
            pixels.extend(mask.tobytes())

    lines = [f"static const unsigned char {name}_pixels[] = {{\n"]
    for offset in range(0, len(pixels), 24):
        lines.append("    " + ",".join(str(value) for value in pixels[offset:offset + 24]) + ",\n")
    lines.extend(["};\n", f"static const Glyph {name}_glyphs[256] = {{\n"])
    for code, *fields in metrics:
        lines.append(f"    [{code}] = {{ " + ", ".join(map(str, fields)) + " },\n")
    lines.append(f"}};\nstatic const Font {name} = {{ {name}_glyphs, {name}_pixels }};\n\n")
    return "".join(lines)


def make_icon():
    scale = 3
    image = Image.new("RGB", (144 * scale, 80 * scale), "#101a28")
    draw = ImageDraw.Draw(image)
    for y in range(80 * scale):
        shade = y / (80 * scale - 1)
        color = (int(15 + 4 * shade), int(25 + 9 * shade), int(39 + 13 * shade))
        draw.line((0, y, image.width, y), fill=color)

    def box(points, radius, fill, outline, width=1):
        draw.rounded_rectangle(tuple(value * scale for value in points), radius * scale,
                               fill=fill, outline=outline, width=width * scale)

    def line(points, fill, width=2):
        draw.line(tuple(value * scale for value in points), fill=fill, width=width * scale)

    box((13, 18, 131, 62), 13, "#1c2d43", "#466382", 2)
    box((48, 26, 96, 54), 4, "#0d1520", "#536d8b")
    for left, height in [(56, 7), (65, 12), (74, 18), (83, 15)]:
        box((left, 49 - height, left + 5, 49), 1, "#6ae6bc", None)
    line((28, 41, 41, 41), "#d5e3f1", 3)
    line((34.5, 34.5, 34.5, 47.5), "#d5e3f1", 3)
    for x, y in [(110, 34), (117, 41), (110, 48), (103, 41)]:
        draw.ellipse(((x - 2) * scale, (y - 2) * scale, (x + 2) * scale, (y + 2) * scale),
                     fill="#8fbaff")
    image.resize((144, 80), Image.Resampling.LANCZOS).save(HERE / "ICON0.PNG", optimize=True)


if __name__ == "__main__":
    faces = [
        ("large_font", "LiberationSans-Bold.ttf", 24),
        ("label_font", "LiberationSans-Bold.ttf", 13),
        ("small_font", "LiberationSans-Regular.ttf", 12),
        ("button_font", "LiberationSans-Regular.ttf", 10),
    ]
    text = "/* Generated by assets.py. See licenses/FONT-LICENSE.txt. */\n\n"
    (HERE / "font.inc").write_text(text + "".join(font_data(*face) for face in faces), encoding="utf-8")
    make_icon()
